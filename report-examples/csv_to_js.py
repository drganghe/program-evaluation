# ── Main ──────────────────────────────────────────────────────────────────

def convert(input_path: Path, output_path: Path) -> None:
    print(f"Reading  : {input_path}")

    with input_path.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    if not rows:
        print("ERROR: CSV has no data rows.")
        sys.exit(1)

    print(f"  Found {len(rows)} report(s)")

    # Build JS objects
    objects = [csv_row_to_js_object(row) for row in rows]
    body = ",\n".join(objects)

    header = JS_HEADER.format(
        date=datetime.now().strftime("%Y-%m-%d %H:%M"),
        source=input_path.name,
    )

    js_content = header + body + JS_FOOTER

    output_path.write_text(js_content, encoding="utf-8")
    print(f"Written  : {output_path}")
    print(f"  {len(rows)} reports exported successfully.")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Convert reports-data.csv → reports-data.js"
    )
    parser.add_argument(
        "positional_input",
        nargs="?",
        help="Input CSV path (positional, optional)",
    )
    parser.add_argument(
        "positional_output",
        nargs="?",
        help="Output JS path (positional, optional)",
    )
    parser.add_argument(
        "--input", "-i",
        default=None,
        help="Input CSV file (default: reports-data.csv)",
    )
    parser.add_argument(
        "--output", "-o",
        default=None,
        help="Output JS file (default: reports-data.js)",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()

    # Named args take priority over positional
    input_path  = Path(args.input  or args.positional_input  or "reports-data.csv")
    output_path = Path(args.output or args.positional_output or "reports-data.js")

    if not input_path.exists():
        print(f"ERROR: Input file not found: {input_path}")
        sys.exit(1)

    convert(input_path, output_path)
