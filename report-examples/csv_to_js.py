#!/usr/bin/env python3
"""
csv_to_js.py
============
Converts reports-data.csv to reports-data.js.

Usage
-----
    python csv_to_js.py                                  # default paths
    python csv_to_js.py input.csv output.js              # custom paths
    python csv_to_js.py --input data.csv --output out.js # named args

CSV conventions (must match):
  - Array fields separated by "; " (semicolon + space)
  - open_access column: TRUE / FALSE (case-insensitive)
  - year and id columns: plain integers
"""

import csv
import json
import sys
import argparse
from pathlib import Path
from datetime import datetime

# ── Column configuration ───────────────────────────────────────────────────
# Fields whose CSV value is a "; "-delimited string → converted to JS array.
ARRAY_FIELDS = {
    "evaluation_type",
    "causal_methods",
    "data_collection",
    "topics",
}

# Fields that should become JS integers (not quoted strings).
INT_FIELDS = {"id", "year"}

# Fields that should become JS booleans.
BOOL_FIELDS = {"open_access"}

# ── Conversion helpers ─────────────────────────────────────────────────────

def parse_array(value: str) -> list[str]:
    """Split a '; '-delimited cell into a stripped list, ignoring empties."""
    return [item.strip() for item in value.split(";") if item.strip()]


def to_js_value(field: str, raw: str) -> str:
    """Return the JavaScript literal representation of a CSV cell value."""
    if field in INT_FIELDS:
        try:
            return str(int(raw))
        except ValueError:
            # Fall through to string if the cell isn't a clean integer
            pass

    if field in BOOL_FIELDS:
        return "true" if raw.strip().upper() == "TRUE" else "false"

    if field in ARRAY_FIELDS:
        items = parse_array(raw)
        inner = ", ".join(json.dumps(item, ensure_ascii=False) for item in items)
        return f"[{inner}]"

    # Default: quoted string
    return json.dumps(raw.strip(), ensure_ascii=False)


def csv_row_to_js_object(row: dict) -> str:
    """Convert one CSV row dict into an indented JS object literal string."""
    lines = []
    for field, raw in row.items():
        if not field:          # skip any blank header columns
            continue
        js_val = to_js_value(field, raw)
        # Rename CSV snake_case keys to camelCase JS keys where needed
        js_key = CSV_TO_JS_KEY.get(field, field)
        lines.append(f"    {js_key}: {js_val}")
    return "  {\n" + ",\n".join(lines) + "\n  }"


# Map CSV column names → JS property names (only where they differ)
CSV_TO_JS_KEY = {
    "evaluation_type": "evaluation_type",
    "causal_methods":  "causal_methods",
    "data_collection": "data_collection",
    "download_url":    "download_url",
    "open_access":     "open_access",
    "org_type":        "org_type",
    # All others are identical in both CSV and JS
}

# ── JS file template ───────────────────────────────────────────────────────

